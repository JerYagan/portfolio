export type TechnologyId = (typeof TECHNOLOGY_OPTIONS)[number]['id'];
export type TechnologyStatus = 'known' | 'learning';
export type CatalogTechnology = { id: TechnologyId; status: TechnologyStatus };
export type LegacyTechnology = { name: string; group?: string; status: TechnologyStatus };
export type StoredTechnology = CatalogTechnology | LegacyTechnology;

const catalogIds = new Set<string>(TECHNOLOGY_OPTIONS.map((item) => item.id));

function asRecord(value: unknown): Record<string, unknown> | null {
  return value && typeof value === 'object' && !Array.isArray(value)
    ? value as Record<string, unknown>
    : null;
}

function matchCatalogTechnology(name: string) {
  const normalized = name.trim().toLowerCase().replace(/[.\s_-]+/g, '');
  const aliases: Record<string, TechnologyId> = {
    html: 'html5',
    html5: 'html5',
    css: 'css3',
    css3: 'css3',
    vue: 'vuedotjs',
    vuejs: 'vuedotjs',
    vuedotjs: 'vuedotjs',
    next: 'nextdotjs',
    nextjs: 'nextdotjs',
    node: 'nodedotjs',
    nodejs: 'nodedotjs',
    tailwind: 'tailwindcss',
  };
  const alias = aliases[normalized];
  if (alias) return alias;
  return TECHNOLOGY_OPTIONS.find((technology) => technology.id === normalized)?.id;
}

export function normalizeStoredTechnologies(value: unknown): StoredTechnology[] {
  if (!Array.isArray(value)) return [];
  const result: StoredTechnology[] = [];
  const seen = new Set<string>();

  for (const raw of value) {
    const item = asRecord(raw);
    if (!item) continue;
    const status: TechnologyStatus = item.status === 'learning' ? 'learning' : 'known';

    if (typeof item.id === 'string' && catalogIds.has(item.id)) {
      if (seen.has(item.id)) continue;
      seen.add(item.id);
      result.push({ id: item.id as TechnologyId, status });
      continue;
    }

    if (typeof item.name !== 'string' || !item.name.trim()) continue;
    const id = matchCatalogTechnology(item.name);
    if (id) {
      if (seen.has(id)) continue;
      seen.add(id);
      result.push({ id, status });
      continue;
    }

    const name = item.name.trim().slice(0, 80);
    const legacyKey = `legacy:${name.toLocaleLowerCase()}`;
    if (seen.has(legacyKey)) continue;
    seen.add(legacyKey);
    result.push({
      name,
      ...(typeof item.group === 'string' && item.group.trim() ? { group: item.group.trim().slice(0, 80) } : {}),
      status,
    });
  }

  return result;
}

export function technologyOption(id: string) {
  return TECHNOLOGY_OPTIONS.find((technology) => technology.id === id);
}

export function technologyIdForLabel(name: string): TechnologyId | undefined {
  return matchCatalogTechnology(name);
}
